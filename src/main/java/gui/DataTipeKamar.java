private void loadData() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(new String[]{"ID Tipe", "Nama Tipe"}, 0);
        try {
            dao.TipeKamarDAO tipeDao = new dao.TipeKamarDAO();
            java.util.List<Object[]> listTipe = tipeDao.getAllTipeKamar();
            
            for (Object[] row : listTipe) {
                model.addRow(row);
            }
            tabelTipe.setModel(model);
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error load data: " + e.getMessage());
        }
    }
    
