    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        try {
            dao.TipeKamarDAO tipeDao = new dao.TipeKamarDAO();
            
            if (txtId.getText().isEmpty()) { 
                tipeDao.insert(txtNama.getText());
                javax.swing.JOptionPane.showMessageDialog(this, "Tipe Kamar Berhasil Disimpan!");
            } else { 
                tipeDao.update(txtId.getText(), txtNama.getText());
                javax.swing.JOptionPane.showMessageDialog(this, "Tipe Kamar Berhasil Diupdate!");
            }
            loadData(); 
            txtId.setText(""); 
            txtNama.setText("");
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Save: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        try {
            dao.TipeKamarDAO tipeDao = new dao.TipeKamarDAO();
            tipeDao.delete(txtId.getText());
            
            javax.swing.JOptionPane.showMessageDialog(this, "Tipe Kamar Berhasil Dihapus!");
            loadData();
            txtId.setText(""); txtNama.setText("");
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Delete: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tabelTipeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelTipeMouseClicked
        // TODO add your handling code here:
        int baris = tabelTipe.getSelectedRow();
        if (baris != -1) {
            txtId.setText(tabelTipe.getValueAt(baris, 0).toString());
            txtNama.setText(tabelTipe.getValueAt(baris, 1).toString());
        }
    }//GEN-LAST:event_tabelTipeMouseClicked

