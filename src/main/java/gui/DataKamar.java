private void loadTipeKamarComboBox() {
        try {
            cmbTipe.removeAllItems();
            cmbTipe.addItem("- Pilih Tipe -");
            
            // Memanggil data menggunakan DAO, tiada lagi raw SQL di sini!
            dao.TipeKamarDAO tipeDao = new dao.TipeKamarDAO();
            java.util.List<Object[]> listTipe = tipeDao.getAllTipeKamar();
            
            // Menggelung (loop) senarai dan memasukkannya ke dalam ComboBox
            for (Object[] row : listTipe) {
                // row[1] mewakili lajur 'nama_tipe'
                cmbTipe.addItem(row[1].toString());
            }
        } catch(Exception e) { 
            utils.LogHelper.error("Error load ComboBox Tipe Kamar: " + e.getMessage()); 
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat daftar tipe kamar!");
        }
    }

private void loadDataTabel() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(new String[]{"Kode", "Tipe", "Kapasitas", "Lantai", "Fasilitas", "Harga", "Status"}, 0);
        try {
            dao.KamarDAO kamarDao = new dao.KamarDAO();
            java.util.List<Object[]> listKamar = kamarDao.getAllKamar();
            
            // Format angka standar Indonesia
            java.text.NumberFormat formatRupiah = java.text.NumberFormat.getInstance(new java.util.Locale("id", "ID"));
            
            for (Object[] row : listKamar) {
                // Mencegat data harga di indeks ke-5 (0: kode, 1: tipe, 2: kap, 3: lan, 4: fas, 5: harga, 6: status)
                int hargaAsli = Integer.parseInt(row[5].toString());
                row[5] = "Rp " + formatRupiah.format(hargaAsli); // Mengubah 450000 menjadi Rp 450.000
                
                model.addRow(row);
            }
            tabelKamar.setModel(model);
        } catch(Exception e) { 
            utils.LogHelper.error("Error Load Data Tabel Kamar: " + e.getMessage());
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal memuat data tabel kamar!");
        }
    }
    
