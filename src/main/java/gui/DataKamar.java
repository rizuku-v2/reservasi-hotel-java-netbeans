    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            
            javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
            fileChooser.setDialogTitle("Simpan Data Export");
            int userSelection = fileChooser.showSaveDialog(this);
            
            if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
                java.io.File fileToSave = fileChooser.getSelectedFile();
                
                java.io.FileWriter fw = new java.io.FileWriter(fileToSave + ".csv");
                java.io.BufferedWriter bw = new java.io.BufferedWriter(fw);

                
                bw.write("Kode Kamar,Tipe,Kapasitas,Lantai,Fasilitas,Harga,Status");
                bw.newLine();

                
                for (int i = 0; i < tabelKamar.getRowCount(); i++) {
                    for (int j = 0; j < tabelKamar.getColumnCount(); j++) {
                        
                        bw.write("\"" + tabelKamar.getValueAt(i, j).toString() + "\"");
                        if (j < tabelKamar.getColumnCount() - 1) {
                            bw.write(",");
                        }
                    }
                    bw.newLine();
                }
                bw.close();
                fw.close();
                
                javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Diexport ke:\n" + fileToSave.getAbsolutePath() + ".csv");
                utils.LogHelper.info("User berhasil melakukan export data kamar."); 
            }
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Export: " + ex.getMessage());
            utils.LogHelper.error("Gagal export data kamar: " + ex.getMessage()); 
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void txtCariKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtCariKeyReleased
        // TODO add your handling code here:
        String keyword = txtCari.getText();
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(new String[]{"Kode", "Tipe", "Kapasitas", "Lantai", "Fasilitas", "Harga", "Status"}, 0);
        
        try {
            dao.KamarDAO kamarDao = new dao.KamarDAO();
            // Memanggil fungsi search yang baru saja kita buat
            java.util.List<Object[]> listKamar = kamarDao.searchKamar(keyword);
            
            // Jangan lupa pasang lagi format Rupiahnya agar tabel pencarian tetap cantik!
            java.text.NumberFormat formatRupiah = java.text.NumberFormat.getInstance(new java.util.Locale("id", "ID"));
            
            for (Object[] row : listKamar) {
                int hargaAsli = Integer.parseInt(row[5].toString());
                row[5] = "Rp " + formatRupiah.format(hargaAsli);
                model.addRow(row);
            }
            tabelKamar.setModel(model);
        } catch(Exception e) { 
            utils.LogHelper.error("Error Live Search: " + e.getMessage());
        }
    }//GEN-LAST:event_txtCariKeyReleased

