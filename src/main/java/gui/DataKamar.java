    private void tabelKamarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelKamarMouseClicked
        // TODO add your handling code here:
        int baris = tabelKamar.getSelectedRow();
        if(baris != -1) {
            txtKode.setText(tabelKamar.getValueAt(baris, 0).toString());
            cmbTipe.setSelectedItem(tabelKamar.getValueAt(baris, 1).toString());
            txtKapasitas.setText(tabelKamar.getValueAt(baris, 2).toString());
            txtLantai.setText(tabelKamar.getValueAt(baris, 3).toString());
            txtFasilitas.setText(tabelKamar.getValueAt(baris, 4).toString());
            
            // TRIK GAIB: Mengembalikan format "Rp 450.000" menjadi angka murni "450000"
            // Sintaks regex [^0-9] artinya: Hapus semua karakter yang BUKAN angka 0 sampai 9
            String hargaRupiah = tabelKamar.getValueAt(baris, 5).toString();
            String hargaMurni = hargaRupiah.replaceAll("[^0-9]", ""); 
            txtHarga.setText(hargaMurni);
            
            cmbStatus.setSelectedItem(tabelKamar.getValueAt(baris, 6).toString());
        }
    }//GEN-LAST:event_tabelKamarMouseClicked

