    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        try {
            if (txtKode.getText().trim().isEmpty() || txtKapasitas.getText().trim().isEmpty() || 
                txtLantai.getText().trim().isEmpty() || txtHarga.getText().trim().isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Harap lengkapi semua data kamar!");
                return;
            }

            dao.KamarDAO kamarDao = new dao.KamarDAO();
            
            // Validasi Duplikat lewat DAO
            if (kamarDao.cekKodeKamar(txtKode.getText())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Kode Kamar '" + txtKode.getText() + "' sudah ada!", "Peringatan", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // MENGAMBIL ID TIPE KAMAR DARI DATABASE BERDASARKAN PILIHAN COMBOBOX
            dao.TipeKamarDAO tipeDao = new dao.TipeKamarDAO();
            int idTipe = tipeDao.getIdTipeByNama(cmbTipe.getSelectedItem().toString());
            
            if (idTipe == 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Silakan pilih tipe kamar yang valid!");
                return;
            }

            int kapasitas = Integer.parseInt(txtKapasitas.getText());
            int lantai = Integer.parseInt(txtLantai.getText());
            int harga = Integer.parseInt(txtHarga.getText());

            // Eksekusi Simpan Data lewat DAO (Sekarang menggunakan idTipe)
            kamarDao.insert(
                txtKode.getText(),
                idTipe,
                kapasitas,
                lantai,
                txtFasilitas.getText(),
                harga,
                cmbStatus.getSelectedItem().toString()
            );
            
            javax.swing.JOptionPane.showMessageDialog(this, "Data Kamar Berhasil Disimpan!");
            utils.LogHelper.info("Berhasil menyimpan data kamar baru: " + txtKode.getText());
            
            loadDataTabel(); 
            bersihkanForm(); 
            
        } catch (NumberFormatException nfe) {
            javax.swing.JOptionPane.showMessageDialog(this, "Kapasitas, Lantai, dan Harga harus berupa angka!", "Error Input", javax.swing.JOptionPane.ERROR_MESSAGE);
            utils.LogHelper.error("Error Format Angka di form kamar: " + nfe.getMessage());
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Save: " + e.getMessage());
            utils.LogHelper.error("Error Save Kamar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

